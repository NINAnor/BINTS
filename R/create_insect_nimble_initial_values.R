# ==============================================================================
# Create initial values for NIMBLE insect model
#
# Creates conservative initial values for the generated NIMBLE model.
#
# Response options:
#   - "biomass"
#   - "diversity"
#   - "both"
#
# Biomass distributions:
#   - "normal"
#   - "lognormal"
#
# Diversity distributions:
#   - "poisson"
#   - "negative_binomial"
#
# Temporal effects:
#   - "none"
#   - "linear"
#   - "cubic_cyclic"
#
# Spatial effects:
#   - "none"
#   - "coordinates"
#   - "autocorrelation"
#
# IMPORTANT:
#
# For temporal_effect = "cubic_cyclic", the temporal spline is represented by
# multiple basis coefficients:
#
#     beta_time_biomass[k]
#
#     beta_time_diversity[k]
#
# The number of coefficients MUST correspond to the number of positive
# eigenvalues retained from the mgcv cyclic-spline penalty matrix.
#
# Therefore this function accepts temporal_basis_penalized and determines:
#
#     n_temporal_basis = ncol(temporal_basis_penalized)
#
# The initial values for the spline coefficients are zero.
#
# ==============================================================================


create_insect_nimble_initial_values <- function(
    
    modelling_data,
    modelCovs,
    covariate_types = NULL,
    
    # --------------------------------------------------------------------------
    # Response specification
    # --------------------------------------------------------------------------
    
    response = "biomass",
    
    biomass_col = "sum_wet_weight",
    
    diversity_col = NULL,
    
    # --------------------------------------------------------------------------
    # Response distributions
    # --------------------------------------------------------------------------
    
    biomass_distribution = "normal",
    
    diversity_distribution = "poisson",
    
    # --------------------------------------------------------------------------
    # Random effects
    # --------------------------------------------------------------------------
    
    random_year = FALSE,
    
    random_locality = FALSE,
    
    random_replicate = FALSE,
    
    # --------------------------------------------------------------------------
    # Column names
    # --------------------------------------------------------------------------
    
    year_col = "year",
    
    locality_col = "locality",
    
    replicate_col = "sampling_name",
    
    # --------------------------------------------------------------------------
    # Temporal effect
    # --------------------------------------------------------------------------
    
    temporal_data = NULL,
    
    temporal_effect = c(
        "none",
        "linear",
        "cubic_cyclic"
    ),
    
    # --------------------------------------------------------------------------
    # Temporal spline basis
    #
    # For cubic_cyclic this should be the already transformed basis:
    #
    #     temporal_basis_penalized
    #
    # generated by create_insect_nimble_model().
    #
    # --------------------------------------------------------------------------
    
    temporal_basis_penalized = NULL,
    
    # --------------------------------------------------------------------------
    # Spatial effect
    # --------------------------------------------------------------------------
    
    spatial_effect = c(
        "none",
        "coordinates",
        "autocorrelation"
    ),
    
    spatial_shared = TRUE,
    
    longitude_col = "longitude",
    
    latitude_col = "latitude",
    
    # --------------------------------------------------------------------------
    # Spatial parameter priors
    #
    # These should match the priors used in
    # create_insect_nimble_model().
    # --------------------------------------------------------------------------
    
    spatial_range_prior = c(
        1000,
        500000
    ),
    
    spatial_sigma_prior = 1,
    
    # --------------------------------------------------------------------------
    # Reproducibility
    # --------------------------------------------------------------------------
    
    seed = NULL
    
) {
    
    
    # ==========================================================================
    # 1. Set seed
    # ==========================================================================
    
    if (!is.null(seed)) {
        
        set.seed(
            seed
        )
        
    }
    
    
    # ==========================================================================
    # 2. Validate response
    # ==========================================================================
    
    response <- match.arg(
        response,
        choices = c(
            "biomass",
            "diversity",
            "both"
        )
    )
    
    
    # ==========================================================================
    # 3. Validate response distributions
    # ==========================================================================
    
    biomass_distribution <- match.arg(
        biomass_distribution,
        choices = c(
            "normal",
            "lognormal"
        )
    )
    
    diversity_distribution <- match.arg(
        diversity_distribution,
        choices = c(
            "poisson",
            "negative_binomial"
        )
    )
    
    
    # ==========================================================================
    # 4. Validate temporal effect
    # ==========================================================================
    
    temporal_effect <- match.arg(
        temporal_effect,
        choices = c(
            "none",
            "linear",
            "cubic_cyclic"
        )
    )
    
    
    # ==========================================================================
    # 5. Validate spatial effect
    # ==========================================================================
    
    spatial_effect <- match.arg(
        spatial_effect,
        choices = c(
            "none",
            "coordinates",
            "autocorrelation"
        )
    )
    
    
    # ==========================================================================
    # 6. Validate spatial_shared
    # ==========================================================================
    
    if (
        !is.logical(spatial_shared) ||
        length(spatial_shared) != 1 ||
        is.na(spatial_shared)
    ) {
        
        stop(
            "'spatial_shared' must be TRUE or FALSE.",
            call. = FALSE
        )
        
    }
    
    
    # ==========================================================================
    # 7. Validate spatial parameter priors
    # ==========================================================================
    
    if (
        !is.numeric(spatial_range_prior) ||
        length(spatial_range_prior) != 2 ||
        any(!is.finite(spatial_range_prior)) ||
        spatial_range_prior[1] <= 0 ||
        spatial_range_prior[2] <= spatial_range_prior[1]
    ) {
        
        stop(
            "'spatial_range_prior' must contain two positive finite values ",
            "with the lower bound smaller than the upper bound.",
            call. = FALSE
        )
        
    }
    
    
    if (
        !is.numeric(spatial_sigma_prior) ||
        length(spatial_sigma_prior) != 1 ||
        !is.finite(spatial_sigma_prior) ||
        spatial_sigma_prior <= 0
    ) {
        
        stop(
            "'spatial_sigma_prior' must be a single positive finite value.",
            call. = FALSE
        )
        
    }
    
    
    # ==========================================================================
    # 8. Determine included responses
    # ==========================================================================
    
    include_biomass <- response %in% c(
        "biomass",
        "both"
    )
    
    include_diversity <- response %in% c(
        "diversity",
        "both"
    )
    
    
    # ==========================================================================
    # 9. Validate modelling data
    # ==========================================================================
    
    if (!is.data.frame(modelling_data)) {
        
        stop(
            "modelling_data must be a data frame.",
            call. = FALSE
        )
        
    }
    
    N <- nrow(
        modelling_data
    )
    
    if (N == 0) {
        
        stop(
            "modelling_data contains no observations.",
            call. = FALSE
        )
        
    }
    
    
    # ==========================================================================
    # 10. Validate response columns
    # ==========================================================================
    
    if (include_biomass) {
        
        if (is.null(biomass_col)) {
            
            stop(
                "biomass_col must be supplied when ",
                "response includes biomass.",
                call. = FALSE
            )
            
        }
        
        if (!biomass_col %in% names(modelling_data)) {
            
            stop(
                "Biomass column not found in modelling_data: ",
                biomass_col,
                call. = FALSE
            )
            
        }
        
    }
    
    
    if (include_diversity) {
        
        if (is.null(diversity_col)) {
            
            stop(
                "diversity_col must be supplied when ",
                "response includes diversity.",
                call. = FALSE
            )
            
        }
        
        if (!diversity_col %in% names(modelling_data)) {
            
            stop(
                "Diversity column not found in modelling_data: ",
                diversity_col,
                call. = FALSE
            )
            
        }
        
    }
    
    
    # ==========================================================================
    # 11. Validate model covariates
    # ==========================================================================
    
    if (missing(modelCovs) || is.null(modelCovs)) {
        
        modelCovs <- character(0)
        
    }
    
    if (!is.character(modelCovs)) {
        
        stop(
            "modelCovs must be a character vector.",
            call. = FALSE
        )
        
    }
    
    if (anyDuplicated(modelCovs)) {
        
        stop(
            "modelCovs contains duplicated covariate names.",
            call. = FALSE
        )
        
    }
    
    
    # ==========================================================================
    # 12. Validate covariate types
    # ==========================================================================
    
    if (length(modelCovs) > 0) {
        
        if (is.null(covariate_types)) {
            
            covariate_types <- setNames(
                rep(
                    "continuous",
                    length(modelCovs)
                ),
                modelCovs
            )
            
        } else {
            
            if (!is.character(covariate_types)) {
                
                stop(
                    "covariate_types must be a character vector.",
                    call. = FALSE
                )
                
            }
            
            invalid_types <- setdiff(
                unique(covariate_types),
                c(
                    "continuous",
                    "categorical"
                )
            )
            
            if (length(invalid_types) > 0) {
                
                stop(
                    "covariate_types must contain only ",
                    "'continuous' or 'categorical'. ",
                    "Invalid type(s): ",
                    paste(
                        invalid_types,
                        collapse = ", "
                    ),
                    call. = FALSE
                )
                
            }
            
            missing_types <- setdiff(
                modelCovs,
                names(covariate_types)
            )
            
            if (length(missing_types) > 0) {
                
                stop(
                    "No covariate type supplied for: ",
                    paste(
                        missing_types,
                        collapse = ", "
                    ),
                    call. = FALSE
                )
                
            }
            
        }
        
    } else {
        
        covariate_types <- character(0)
        
    }
    
    
    # ==========================================================================
    # 13. Separate covariates
    # ==========================================================================
    
    continuous_covariates <- modelCovs[
        covariate_types[modelCovs] == "continuous"
    ]
    
    categorical_covariates <- modelCovs[
        covariate_types[modelCovs] == "categorical"
    ]
    
    
    # ==========================================================================
    # 14. Validate spatial coordinates
    # ==========================================================================
    
    if (
        spatial_effect %in%
        c(
            "coordinates",
            "autocorrelation"
        )
    ) {
        
        required_spatial_cols <- c(
            longitude_col,
            latitude_col
        )
        
        missing_spatial_cols <- setdiff(
            required_spatial_cols,
            names(modelling_data)
        )
        
        if (length(missing_spatial_cols) > 0) {
            
            stop(
                "The following spatial coordinate columns are missing from ",
                "modelling_data: ",
                paste(
                    missing_spatial_cols,
                    collapse = ", "
                ),
                call. = FALSE
            )
            
        }
        
        longitude <- modelling_data[[longitude_col]]
        latitude <- modelling_data[[latitude_col]]
        
        if (!is.numeric(longitude)) {
            
            stop(
                "'",
                longitude_col,
                "' must be numeric.",
                call. = FALSE
            )
            
        }
        
        if (!is.numeric(latitude)) {
            
            stop(
                "'",
                latitude_col,
                "' must be numeric.",
                call. = FALSE
            )
            
        }
        
        if (
            anyNA(longitude) ||
            anyNA(latitude)
        ) {
            
            stop(
                "Missing longitude/latitude values are not allowed when ",
                "a spatial effect is used.",
                call. = FALSE
            )
            
        }
        
        if (
            any(!is.finite(longitude)) ||
            any(!is.finite(latitude))
        ) {
            
            stop(
                "Longitude and latitude must contain only finite values.",
                call. = FALSE
            )
            
        }
        
        if (
            any(
                longitude < -180 |
                    longitude > 180
            )
        ) {
            
            stop(
                "Longitude values must be between -180 and 180 degrees.",
                call. = FALSE
            )
            
        }
        
        if (
            any(
                latitude < -90 |
                    latitude > 90
            )
        ) {
            
            stop(
                "Latitude values must be between -90 and 90 degrees.",
                call. = FALSE
            )
            
        }
        
    }
    
    
    # ==========================================================================
    # 15. Initialise output
    # ==========================================================================
    
    initial_values <- list()
    
    
    # ==========================================================================
    # 16. Biomass initial values
    # ==========================================================================
    
    if (include_biomass) {
        
        biomass <- modelling_data[[biomass_col]]
        
        # ----------------------------------------------------------------------
        # Validate numeric response
        # ----------------------------------------------------------------------
        
        if (!is.numeric(biomass)) {
            
            stop(
                "Biomass response must be numeric.",
                call. = FALSE
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Validate finite values
        # ----------------------------------------------------------------------
        
        if (anyNA(biomass)) {
            
            stop(
                "Missing values found in biomass response.",
                call. = FALSE
            )
            
        }
        
        if (any(!is.finite(biomass))) {
            
            stop(
                "Non-finite values found in biomass response.",
                call. = FALSE
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Log-normal biomass requires positive observations
        # ----------------------------------------------------------------------
        
        if (biomass_distribution == "lognormal") {
            
            if (any(biomass <= 0)) {
                
                stop(
                    "Log-normal biomass requires strictly positive observations. ",
                    "Found ",
                    sum(biomass <= 0),
                    " observation(s) <= 0.",
                    call. = FALSE
                )
                
            }
            
        }
        
        # ----------------------------------------------------------------------
        # Biomass intercept
        # ----------------------------------------------------------------------
        
        if (biomass_distribution == "normal") {
            
            initial_values[[
                "alpha_biomass"
            ]] <- mean(
                biomass
            )
            
        } else {
            
            # For a log-normal model, alpha is on the log scale.
            
            initial_values[[
                "alpha_biomass"
            ]] <- mean(
                log(biomass)
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Biomass regression coefficients
        # ----------------------------------------------------------------------
        
        if (length(continuous_covariates) > 0) {
            
            initial_values[[
                "beta_biomass"
            ]] <- rep(
                0,
                length(continuous_covariates)
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Biomass residual precision
        # ----------------------------------------------------------------------
        
        if (biomass_distribution == "normal") {
            
            biomass_sd <- stats::sd(
                biomass
            )
            
        } else {
            
            biomass_sd <- stats::sd(
                log(biomass)
            )
            
        }
        
        if (
            !is.finite(biomass_sd) ||
            biomass_sd <= 0
        ) {
            
            biomass_sd <- 1
            
        }
        
        initial_values[[
            "tau_biomass"
        ]] <- 1 / biomass_sd^2
        
    }
    
    
    # ==========================================================================
    # 17. Diversity initial values
    # ==========================================================================
    
    if (include_diversity) {
        
        diversity <- modelling_data[[diversity_col]]
        
        # ----------------------------------------------------------------------
        # Validate numeric response
        # ----------------------------------------------------------------------
        
        if (!is.numeric(diversity)) {
            
            stop(
                "Diversity response must be numeric.",
                call. = FALSE
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Validate missing and non-finite values
        # ----------------------------------------------------------------------
        
        if (anyNA(diversity)) {
            
            stop(
                "Missing values found in diversity response.",
                call. = FALSE
            )
            
        }
        
        if (any(!is.finite(diversity))) {
            
            stop(
                "Non-finite values found in diversity response.",
                call. = FALSE
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Validate count response
        # ----------------------------------------------------------------------
        
        if (
            diversity_distribution %in%
            c(
                "poisson",
                "negative_binomial"
            )
        ) {
            
            if (any(diversity < 0)) {
                
                stop(
                    diversity_distribution,
                    " diversity requires non-negative observations.",
                    call. = FALSE
                )
                
            }
            
            if (any(diversity != floor(diversity))) {
                
                stop(
                    diversity_distribution,
                    " diversity requires integer-valued observations.",
                    call. = FALSE
                )
                
            }
            
        }
        
        # ----------------------------------------------------------------------
        # Diversity intercept
        # ----------------------------------------------------------------------
        
        if (
            diversity_distribution %in%
            c(
                "poisson",
                "negative_binomial"
            )
        ) {
            
            mean_diversity <- mean(
                diversity
            )
            
            # Avoid log(0)
            
            if (mean_diversity <= 0) {
                
                mean_diversity <- 0.1
                
            }
            
            initial_values[[
                "alpha_diversity"
            ]] <- log(
                mean_diversity
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Diversity regression coefficients
        # ----------------------------------------------------------------------
        
        if (length(continuous_covariates) > 0) {
            
            initial_values[[
                "beta_diversity"
            ]] <- rep(
                0,
                length(continuous_covariates)
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Negative-binomial dispersion
        # ----------------------------------------------------------------------
        
        if (
            diversity_distribution ==
            "negative_binomial"
        ) {
            
            # ------------------------------------------------------------------
            # Method-of-moments initial value:
            #
            #   Var(Y) = mu + mu^2 / size
            #
            # therefore:
            #
            #   size = mu^2 / (Var(Y) - mu)
            # ------------------------------------------------------------------
            
            mean_diversity <- mean(
                diversity
            )
            
            variance_diversity <- stats::var(
                diversity
            )
            
            if (
                is.finite(mean_diversity) &&
                is.finite(variance_diversity) &&
                variance_diversity > mean_diversity &&
                mean_diversity > 0
            ) {
                
                size_diversity <- (
                    mean_diversity^2 /
                        (
                            variance_diversity -
                                mean_diversity
                        )
                )
                
            } else {
                
                size_diversity <- 10
                
            }
            
            # ------------------------------------------------------------------
            # Keep initial value numerically reasonable
            # ------------------------------------------------------------------
            
            size_diversity <- max(
                0.1,
                min(
                    size_diversity,
                    1000
                )
            )
            
            initial_values[[
                "size_diversity"
            ]] <- size_diversity
            
        }
        
    }
    
    
    # ==========================================================================
    # 18. Categorical covariates as random effects
    # ==========================================================================
    
    if (length(categorical_covariates) > 0) {
        
        for (cov in categorical_covariates) {
            
            # ------------------------------------------------------------------
            # Check covariate exists
            # ------------------------------------------------------------------
            
            if (!cov %in% names(modelling_data)) {
                
                stop(
                    "Categorical covariate not found in modelling_data: ",
                    cov,
                    call. = FALSE
                )
                
            }
            
            cov_values <- modelling_data[[cov]]
            
            # ------------------------------------------------------------------
            # Check missing values
            # ------------------------------------------------------------------
            
            if (anyNA(cov_values)) {
                
                stop(
                    "Missing values found in categorical covariate: ",
                    cov,
                    ".",
                    call. = FALSE
                )
                
            }
            
            # ------------------------------------------------------------------
            # Convert to factor
            # ------------------------------------------------------------------
            
            cov_factor <- factor(
                cov_values
            )
            
            n_levels <- nlevels(
                cov_factor
            )
            
            # ------------------------------------------------------------------
            # Valid NIMBLE name
            # ------------------------------------------------------------------
            
            cov_clean <- make.names(
                cov
            )
            
            # ------------------------------------------------------------------
            # Biomass random effect
            # ------------------------------------------------------------------
            
            if (include_biomass) {
                
                initial_values[[
                    paste0(
                        cov_clean,
                        "_effect_biomass"
                    )
                ]] <- rep(
                    0,
                    n_levels
                )
                
                initial_values[[
                    paste0(
                        "tau_",
                        cov_clean,
                        "_biomass"
                    )
                ]] <- 1
                
            }
            
            # ------------------------------------------------------------------
            # Diversity random effect
            # ------------------------------------------------------------------
            
            if (include_diversity) {
                
                initial_values[[
                    paste0(
                        cov_clean,
                        "_effect_diversity"
                    )
                ]] <- rep(
                    0,
                    n_levels
                )
                
                initial_values[[
                    paste0(
                        "tau_",
                        cov_clean,
                        "_diversity"
                    )
                ]] <- 1
                
            }
            
        }
        
    }
    
    
    # ==========================================================================
    # 19. Year random effect
    # ==========================================================================
    
    if (random_year) {
        
        # ----------------------------------------------------------------------
        # Check column
        # ----------------------------------------------------------------------
        
        if (!year_col %in% names(modelling_data)) {
            
            stop(
                "Year column not found in modelling_data: ",
                year_col,
                call. = FALSE
            )
            
        }
        
        year_values <- modelling_data[[year_col]]
        
        # ----------------------------------------------------------------------
        # Check missing values
        # ----------------------------------------------------------------------
        
        if (anyNA(year_values)) {
            
            stop(
                "Missing values found in year column.",
                call. = FALSE
            )
            
        }
        
        n_year <- dplyr::n_distinct(
            year_values
        )
        
        # ----------------------------------------------------------------------
        # Biomass year effect
        # ----------------------------------------------------------------------
        
        if (include_biomass) {
            
            initial_values[[
                "year_effect_biomass"
            ]] <- rep(
                0,
                n_year
            )
            
            initial_values[[
                "tau_year_biomass"
            ]] <- 1
            
        }
        
        # ----------------------------------------------------------------------
        # Diversity year effect
        # ----------------------------------------------------------------------
        
        if (include_diversity) {
            
            initial_values[[
                "year_effect_diversity"
            ]] <- rep(
                0,
                n_year
            )
            
            initial_values[[
                "tau_year_diversity"
            ]] <- 1
            
        }
        
    }
    
    
    # ==========================================================================
    # 20. Locality random effect
    # ==========================================================================
    
    if (random_locality) {
        
        # ----------------------------------------------------------------------
        # Check column
        # ----------------------------------------------------------------------
        
        if (!locality_col %in% names(modelling_data)) {
            
            stop(
                "Locality column not found in modelling_data: ",
                locality_col,
                call. = FALSE
            )
            
        }
        
        locality_values <- modelling_data[[locality_col]]
        
        # ----------------------------------------------------------------------
        # Check missing values
        # ----------------------------------------------------------------------
        
        if (anyNA(locality_values)) {
            
            stop(
                "Missing values found in locality column.",
                call. = FALSE
            )
            
        }
        
        n_locality <- dplyr::n_distinct(
            locality_values
        )
        
        # ----------------------------------------------------------------------
        # Biomass locality effect
        # ----------------------------------------------------------------------
        
        if (include_biomass) {
            
            initial_values[[
                "locality_effect_biomass"
            ]] <- rep(
                0,
                n_locality
            )
            
            initial_values[[
                "tau_locality_biomass"
            ]] <- 1
            
        }
        
        # ----------------------------------------------------------------------
        # Diversity locality effect
        # ----------------------------------------------------------------------
        
        if (include_diversity) {
            
            initial_values[[
                "locality_effect_diversity"
            ]] <- rep(
                0,
                n_locality
            )
            
            initial_values[[
                "tau_locality_diversity"
            ]] <- 1
            
        }
        
    }
    
    
    # ==========================================================================
    # 21. Replicate random effect
    #
    # Replicate numbers are extracted from replicate_col and then indexed within
    # locality × year, matching create_insect_nimble_constants().
    #
    # ==========================================================================
    
    if (random_replicate) {
        
        # ----------------------------------------------------------------------
        # Check replicate column
        # ----------------------------------------------------------------------
        
        if (is.null(replicate_col)) {
            
            stop(
                "replicate_col must be supplied when ",
                "random_replicate = TRUE.",
                call. = FALSE
            )
            
        }
        
        if (!replicate_col %in% names(modelling_data)) {
            
            stop(
                "Replicate column not found in modelling_data: ",
                replicate_col,
                call. = FALSE
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Check grouping variables
        # ----------------------------------------------------------------------
        
        required_replicate_vars <- c(
            "locality",
            "year"
        )
        
        missing_replicate_vars <- setdiff(
            required_replicate_vars,
            names(modelling_data)
        )
        
        if (length(missing_replicate_vars) > 0) {
            
            stop(
                "The following columns are required to construct ",
                "replicate IDs: ",
                paste(
                    missing_replicate_vars,
                    collapse = ", "
                ),
                call. = FALSE
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Extract replicate number
        # ----------------------------------------------------------------------
        
        replicate_number <- suppressWarnings(
            as.numeric(
                sub(
                    ".*-",
                    "",
                    as.character(
                        modelling_data[[replicate_col]]
                    )
                )
            )
        )
        
        # ----------------------------------------------------------------------
        # Validate extracted replicate numbers
        # ----------------------------------------------------------------------
        
        if (anyNA(replicate_number)) {
            
            bad_values <- unique(
                modelling_data[[replicate_col]][
                    is.na(replicate_number)
                ]
            )
            
            stop(
                "Could not extract numeric replicate numbers from '",
                replicate_col,
                "'. Problematic value(s): ",
                paste(
                    bad_values,
                    collapse = ", "
                ),
                call. = FALSE
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Construct replicate IDs within locality × year
        # ----------------------------------------------------------------------
        
        replicates <- modelling_data |>
            dplyr::transmute(
                locality = .data$locality,
                year = .data$year,
                replicate_number = replicate_number
            ) |>
            dplyr::group_by(
                locality,
                year
            ) |>
            dplyr::mutate(
                sampling_id = as.integer(
                    factor(
                        replicate_number
                    )
                )
            ) |>
            dplyr::ungroup()
        
        # ----------------------------------------------------------------------
        # Validate replicate IDs
        # ----------------------------------------------------------------------
        
        if (anyNA(replicates$sampling_id)) {
            
            stop(
                "Missing values found in replicate IDs.",
                call. = FALSE
            )
            
        }
        
        n_replicate <- max(
            replicates$sampling_id
        )
        
        # ----------------------------------------------------------------------
        # Biomass replicate effect
        # ----------------------------------------------------------------------
        
        if (include_biomass) {
            
            initial_values[[
                "replicate_effect_biomass"
            ]] <- rep(
                0,
                n_replicate
            )
            
            initial_values[[
                "tau_replicate_biomass"
            ]] <- 1
            
        }
        
        # ----------------------------------------------------------------------
        # Diversity replicate effect
        # ----------------------------------------------------------------------
        
        if (include_diversity) {
            
            initial_values[[
                "replicate_effect_diversity"
            ]] <- rep(
                0,
                n_replicate
            )
            
            initial_values[[
                "tau_replicate_diversity"
            ]] <- 1
            
        }
        
    }
    
    
    # ==========================================================================
    # 22. Temporal effect
    #
    # IMPORTANT:
    #
    #   "linear":
    #
    #       beta_time_* is a scalar.
    #
    #   "cubic_cyclic":
    #
    #       beta_time_* is a vector with one element per retained positive
    #       eigenvalue of the cyclic-spline penalty matrix.
    #
    # The basis itself is supplied to the model function, not initial values.
    #
    # ==========================================================================
    
    if (temporal_effect != "none") {
        
        # ----------------------------------------------------------------------
        # Check temporal data
        # ----------------------------------------------------------------------
        
        if (is.null(temporal_data)) {
            
            stop(
                "temporal_data must be supplied when ",
                "temporal_effect = '",
                temporal_effect,
                "'.",
                call. = FALSE
            )
            
        }
        
        if (
            length(temporal_data) != N
        ) {
            
            stop(
                "temporal_data must have the same number of ",
                "observations as modelling_data.",
                call. = FALSE
            )
            
        }
        
        if (!is.numeric(temporal_data)) {
            
            stop(
                "temporal_data must be numeric.",
                call. = FALSE
            )
            
        }
        
        if (
            any(
                !is.finite(temporal_data)
            )
        ) {
            
            stop(
                "temporal_data contains NA, NaN, or Inf values.",
                call. = FALSE
            )
            
        }
        
        # ----------------------------------------------------------------------
        # Linear temporal effect
        # ----------------------------------------------------------------------
        
        if (temporal_effect == "linear") {
            
            if (include_biomass) {
                
                initial_values[[
                    "beta_time_biomass"
                ]] <- 0
                
            }
            
            if (include_diversity) {
                
                initial_values[[
                    "beta_time_diversity"
                ]] <- 0
                
            }
            
        }
        
        # ----------------------------------------------------------------------
        # Cubic cyclic spline
        # ----------------------------------------------------------------------
        
        if (temporal_effect == "cubic_cyclic") {
            
            # ------------------------------------------------------------------
            # The supplied basis must already be the positive-eigenvalue basis.
            #
            # That is:
            #
            #   temporal_basis_penalized =
            #       temporal_basis %*% temporal_penalty_eigenvectors
            #
            # from create_insect_nimble_model().
            # ------------------------------------------------------------------
            
            if (is.null(temporal_basis_penalized)) {
                
                stop(
                    "temporal_basis_penalized must be supplied when ",
                    "temporal_effect = 'cubic_cyclic'. ",
                    "It must be the basis after projection onto the ",
                    "positive-eigenvalue subspace of the mgcv penalty matrix.",
                    call. = FALSE
                )
                
            }
            
            if (!is.matrix(temporal_basis_penalized)) {
                
                stop(
                    "temporal_basis_penalized must be a numeric matrix.",
                    call. = FALSE
                )
                
            }
            
            if (!is.numeric(temporal_basis_penalized)) {
                
                stop(
                    "temporal_basis_penalized must be numeric.",
                    call. = FALSE
                )
                
            }
            
            if (
                nrow(temporal_basis_penalized) != N
            ) {
                
                stop(
                    "The number of rows in temporal_basis_penalized ",
                    "must equal the number of observations in modelling_data. ",
                    "Expected: ",
                    N,
                    "; supplied: ",
                    nrow(temporal_basis_penalized),
                    ".",
                    call. = FALSE
                )
                
            }
            
            if (
                any(
                    !is.finite(
                        temporal_basis_penalized
                    )
                )
            ) {
                
                stop(
                    "temporal_basis_penalized contains non-finite values.",
                    call. = FALSE
                )
                
            }
            
            n_temporal_basis <- ncol(
                temporal_basis_penalized
            )
            
            if (
                n_temporal_basis < 1
            ) {
                
                stop(
                    "temporal_basis_penalized contains no retained ",
                    "positive-eigenvalue basis functions.",
                    call. = FALSE
                )
                
            }
            
            # ------------------------------------------------------------------
            # Initialise every retained spline coefficient at zero.
            #
            # This is deliberately vector-valued.
            # ------------------------------------------------------------------
            
            if (include_biomass) {
                
                initial_values[[
                    "beta_time_biomass"
                ]] <- rep(
                    0,
                    n_temporal_basis
                )
                
                # Initial precision for the spline penalty.
                #
                # The actual prior is:
                #
                #   beta_k ~ N(
                #       0,
                #       1 / (tau_temporal_biomass * lambda_k)
                #   )
                #
                # so tau is initialised conservatively at 1.
                
                initial_values[[
                    "temporal_tau_biomass"
                ]] <- 1
                
            }
            
            if (include_diversity) {
                
                initial_values[[
                    "beta_time_diversity"
                ]] <- rep(
                    0,
                    n_temporal_basis
                )
                
                initial_values[[
                    "temporal_tau_diversity"
                ]] <- 1
                
            }
            
        }
        
    }
    
    
    # ==========================================================================
    # 23. Spatial effect
    # ==========================================================================
    
    if (
        spatial_effect %in%
        c(
            "coordinates",
            "autocorrelation"
        )
    ) {
        
        # =========================================================================
        # 23A. Coordinate spatial effect
        # =========================================================================
        
        if (spatial_effect == "coordinates") {
            
            # ------------------------------------------------------------------
            # Shared spatial coordinate coefficients
            #
            # The same spatial trend is applied to both responses.
            #
            # The coordinates supplied to the model are standardised around
            # zero, therefore zero is a natural initial value.
            # ------------------------------------------------------------------
            
            initial_values[[
                "beta_longitude_spatial"
            ]] <- 0
            
            initial_values[[
                "beta_latitude_spatial"
            ]] <- 0
            
        }
        
        
        # =========================================================================
        # 23B. Spatial autocorrelation
        # =========================================================================
        
        if (spatial_effect == "autocorrelation") {
            
            # ------------------------------------------------------------------
            # Determine the number of unique spatial locations.
            #
            # This must exactly match create_insect_nimble_constants().
            # ------------------------------------------------------------------
            
            longitude <- modelling_data[[longitude_col]]
            
            latitude <- modelling_data[[latitude_col]]
            
            # ------------------------------------------------------------------
            # Convert coordinates to sf
            # ------------------------------------------------------------------
            
            spatial_points <- modelling_data |>
                dplyr::select(
                    dplyr::all_of(
                        c(
                            longitude_col,
                            latitude_col
                        )
                    )
                ) |>
                sf::st_as_sf(
                    coords = c(
                        longitude_col,
                        latitude_col
                    ),
                    crs = 4326,
                    remove = FALSE
                )
            
            # ------------------------------------------------------------------
            # Transform to EPSG:25833
            # ------------------------------------------------------------------
            
            spatial_points_projected <- spatial_points |>
                sf::st_transform(
                    crs = 25833
                )
            
            # ------------------------------------------------------------------
            # Extract projected coordinates
            # ------------------------------------------------------------------
            
            xy <- sf::st_coordinates(
                spatial_points_projected
            )
            
            # ------------------------------------------------------------------
            # Construct exactly the same spatial key as the constants function
            # ------------------------------------------------------------------
            
            spatial_key <- paste(
                round(
                    xy[, 1],
                    6
                ),
                round(
                    xy[, 2],
                    6
                ),
                sep = "_"
            )
            
            n_spatial <- length(
                unique(
                    spatial_key
                )
            )
            
            if (n_spatial < 1) {
                
                stop(
                    "No unique spatial locations were identified.",
                    call. = FALSE
                )
                
            }
            
            # =================================================================
            # Shared spatial process
            # =================================================================
            
            if (spatial_shared) {
                
                # ----------------------------------------------------------------
                # Latent spatial process
                # ----------------------------------------------------------------
                
                initial_values[[
                    "spatial_effect"
                ]] <- rep(
                    0,
                    n_spatial
                )
                
                # ----------------------------------------------------------------
                # Spatial range
                # ----------------------------------------------------------------
                
                initial_values[[
                    "rho_spatial"
                ]] <- mean(
                    spatial_range_prior
                )
                
                # ----------------------------------------------------------------
                # Spatial standard deviation
                # ----------------------------------------------------------------
                
                initial_values[[
                    "sigma_spatial"
                ]] <- max(
                    0.5,
                    spatial_sigma_prior
                )
                
                # ----------------------------------------------------------------
                # Response-specific spatial loadings
                # ----------------------------------------------------------------
                
                if (include_biomass) {
                    
                    initial_values[[
                        "lambda_spatial_biomass"
                    ]] <- 0
                    
                }
                
                if (include_diversity) {
                    
                    initial_values[[
                        "lambda_spatial_diversity"
                    ]] <- 0
                    
                }
                
            }
            
            
            # =================================================================
            # Separate spatial processes
            # =================================================================
            
            if (!spatial_shared) {
                
                # ----------------------------------------------------------------
                # Biomass spatial process
                # ----------------------------------------------------------------
                
                if (include_biomass) {
                    
                    initial_values[[
                        "spatial_effect_biomass"
                    ]] <- rep(
                        0,
                        n_spatial
                    )
                    
                    initial_values[[
                        "rho_spatial_biomass"
                    ]] <- mean(
                        spatial_range_prior
                    )
                    
                    initial_values[[
                        "sigma_spatial_biomass"
                    ]] <- max(
                        0.5,
                        spatial_sigma_prior
                    )
                    
                    initial_values[[
                        "lambda_spatial_biomass"
                    ]] <- 0
                    
                }
                
                
                # ----------------------------------------------------------------
                # Diversity spatial process
                # ----------------------------------------------------------------
                
                if (include_diversity) {
                    
                    initial_values[[
                        "spatial_effect_diversity"
                    ]] <- rep(
                        0,
                        n_spatial
                    )
                    
                    initial_values[[
                        "rho_spatial_diversity"
                    ]] <- mean(
                        spatial_range_prior
                    )
                    
                    initial_values[[
                        "sigma_spatial_diversity"
                    ]] <- max(
                        0.5,
                        spatial_sigma_prior
                    )
                    
                    initial_values[[
                        "lambda_spatial_diversity"
                    ]] <- 0
                    
                }
                
            }
            
        }
        
    }
    
    
    # ==========================================================================
    # 24. Return initial values
    # ==========================================================================
    
    initial_values
    
}